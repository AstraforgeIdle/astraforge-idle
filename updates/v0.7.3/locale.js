const storageKey='astraforge_site_language_v1';
const originalText=new WeakMap();
const originalAttrs=new WeakMap();
let language='pt-BR';
try { language=localStorage.getItem(storageKey)==='en'?'en':'pt-BR'; } catch {}
const translate=value=>language==='en'?(english[value]??value):value;
const originalTitle=document.title;
const description=document.querySelector('meta[name="description"]');
const originalDescription=description?.content;
function renderLanguage(){
  document.documentElement.lang=language==='en'?'en':'pt-BR';
  document.title=translate(originalTitle);
  if(description&&originalDescription)description.content=translate(originalDescription);
  const walker=document.createTreeWalker(document.body,NodeFilter.SHOW_TEXT);
  while(walker.nextNode()){
    const node=walker.currentNode;
    if(!node.parentElement||node.parentElement.closest('script,style,noscript,template,svg'))continue;
    if(!originalText.has(node))originalText.set(node,node.nodeValue);
    const source=originalText.get(node),value=source.trim();
    if(value)node.nodeValue=source.replace(value,translate(value));
  }
  for(const element of document.querySelectorAll('[alt],[title],[aria-label],[placeholder],[data-title]')){
    let attrs=originalAttrs.get(element);
    if(!attrs){attrs={};originalAttrs.set(element,attrs);}
    for(const name of ['alt','title','aria-label','placeholder','data-title']){
      if(!(name in attrs)&&element.hasAttribute(name))attrs[name]=element.getAttribute(name);
      if(name in attrs)element.setAttribute(name,translate(attrs[name]));
    }
  }
  for(const button of document.querySelectorAll('.patch-language-picker button')){
    const selected=button.dataset.siteLang===language;
    button.setAttribute('aria-pressed',String(selected));
  }
  const picker=document.querySelector('.patch-language-picker');
  if(picker)picker.setAttribute('aria-label',language==='en'?'Website language':'Idioma do site');
  const back=document.querySelector('.patch-back');
  if(back)back.textContent=translate('← Voltar às atualizações');
}
for(const button of document.querySelectorAll('.patch-language-picker button')){
  button.addEventListener('click',()=>{
    language=button.dataset.siteLang==='en'?'en':'pt-BR';
    try{localStorage.setItem(storageKey,language);}catch{}
    renderLanguage();
  });
}
