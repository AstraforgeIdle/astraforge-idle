const storageKey = 'astraforge_site_language_v1';
const textSource = new WeakMap();
const attributeSource = new WeakMap();
let language = 'pt-BR';
try { language = localStorage.getItem(storageKey) === 'en' ? 'en' : 'pt-BR'; } catch { /* storage optional */ }

export function getLanguage() { return language; }
export function t(phrase) { return language === 'en' ? (english[phrase] || phrase) : phrase; }

export function translateSubtree(root = document) {
  const elementRoot = root.nodeType === 9 ? root.documentElement : root;
  if (!elementRoot) return;
  const walker = document.createTreeWalker(elementRoot, NodeFilter.SHOW_TEXT);
  const textNodes = [];
  while (walker.nextNode()) {
    const node = walker.currentNode;
    if (!node.parentElement || node.parentElement.closest('script,style,noscript,template,svg')) continue;
    textNodes.push(node);
  }
  for (const node of textNodes) {
    if (!textSource.has(node)) textSource.set(node, node.nodeValue);
    const original = textSource.get(node);
    const trimmed = original.trim();
    if (!trimmed) continue;
    const translated = t(trimmed);
    node.nodeValue = original.replace(trimmed, translated);
  }
  const attrs = ['alt', 'aria-label', 'placeholder', 'title', 'data-caption'];
  const elements = [elementRoot, ...elementRoot.querySelectorAll('*')];
  for (const el of elements) {
    if (el.closest('script,style,noscript,template,svg')) continue;
    if (!attributeSource.has(el)) attributeSource.set(el, new Map());
    const originals = attributeSource.get(el);
    for (const attr of attrs) {
      if (!originals.has(attr) && el.hasAttribute(attr)) originals.set(attr, el.getAttribute(attr));
      if (originals.has(attr)) el.setAttribute(attr, t(originals.get(attr)));
    }
    if (el.matches('meta[name="description"],meta[property="og:description"],meta[property="og:title"],meta[property="og:image:alt"]')) {
      if (!originals.has('content')) originals.set('content', el.getAttribute('content') || '');
      el.setAttribute('content', t(originals.get('content')));
    }
  }
  if (elementRoot === document.documentElement) {
    document.documentElement.lang = language === 'en' ? 'en' : 'pt-BR';
    const ogLocale = document.querySelector('meta[property="og:locale"]');
    if (ogLocale) ogLocale.content = language === 'en' ? 'en_US' : 'pt_BR';
    if (!attributeSource.has(document.documentElement)) attributeSource.set(document.documentElement,new Map());
    const originalTitle = document.documentElement;
    const cache = attributeSource.get(originalTitle);
    if (!cache.has('pageTitle')) cache.set('pageTitle',document.title);
    document.title = t(cache.get('pageTitle'));
  }
}

export function setLanguage(next) {
  const selected = next === 'en' ? 'en' : 'pt-BR';
  if (selected === language) return;
  language = selected;
  try { localStorage.setItem(storageKey, selected); } catch { /* storage optional */ }
  translateSubtree();
  document.dispatchEvent(new CustomEvent('astraforge:languagechange', { detail: { language } }));
  updatePicker();
}

function updatePicker() {
  for (const button of document.querySelectorAll('[data-site-lang]')) {
    const chosen = (button.dataset.siteLang === 'en' ? 'en' : 'pt-BR') === language;
    button.setAttribute('aria-pressed', String(chosen));
    button.classList.toggle('active', chosen);
  }
  const group = document.querySelector('[data-language-picker]');
  if (group) group.setAttribute('aria-label', language === 'en' ? 'Website language' : 'Idioma do site');
}

export function mountLanguagePicker() {
  if (!document.querySelector('[data-language-picker]')) {
    const header = document.querySelector('.site-header .header-inner');
    if (header) {
      const picker = document.createElement('div');
      picker.className = 'language-picker';
      picker.setAttribute('role', 'group');
      picker.dataset.languagePicker = '';
      picker.innerHTML = '<button type="button" data-site-lang="pt-BR" aria-label="Português do Brasil" title="Português">🇧🇷 <span>PT</span></button><button type="button" data-site-lang="en" aria-label="English" title="English">🇺🇸 <span>EN</span></button>';
      header.append(picker);
      for (const button of picker.querySelectorAll('button')) button.addEventListener('click', () => setLanguage(button.dataset.siteLang));
    }
  }
  translateSubtree();
  updatePicker();
}
